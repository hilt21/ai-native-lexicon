import { pathWithBase } from './catalog';
export type Locale = 'en' | 'zh-CN';
export function routeLocale(url: URL): Locale {
  const path = url.pathname.slice(import.meta.env.BASE_URL.replace(/\/$/, '').length);
  return path === '/zh-cn' || path.startsWith('/zh-cn/') ? 'zh-CN' : 'en';
}
export function localePath(path: string, locale: Locale = 'en') {
  if (!path.startsWith('/') || path.startsWith('/zh-cn/') || path === '/zh-cn') throw new Error(`Expected canonical route: ${path}`);
  return pathWithBase(locale === 'zh-CN' ? `/zh-cn${path}` : path);
}
export function rootPath(url: URL) {
  const path = url.pathname.slice(import.meta.env.BASE_URL.replace(/\/$/, '').length) || '/';
  return path.startsWith('/zh-cn/') ? path.slice('/zh-cn'.length) : path;
}
